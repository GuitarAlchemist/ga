namespace GeoTiles;

using System.Globalization;
using System.Text;

/// <summary>A line of text as pixels, in a 5 by 7 font of capitals, digits and a little punctuation: enough to
/// show an attribution inside the picture, where the terms of the data ask for it, without a font file.</summary>
public static class Caption
{
