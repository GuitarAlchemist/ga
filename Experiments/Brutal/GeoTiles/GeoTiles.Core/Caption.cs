    /// <summary>What is drawn for <paramref name="text"/>: capitals without accents, "(C)" for the copyright sign,
    /// "?" for what the font does not have.</summary>
    public static string Drawn(string text)
    {
        var plain = new StringBuilder();
        foreach (var c in text.Replace("©", "(C)").Normalize(NormalizationForm.FormD))
        {
            if (CharUnicodeInfo.GetUnicodeCategory(c) == UnicodeCategory.NonSpacingMark)
            {
                continue;
            }

            var upper = char.ToUpperInvariant(c);
            plain.Append(Glyphs.ContainsKey(upper) ? upper : '?');
        }

        return plain.ToString();
    }

    /// <summary>White text on a dark band, RGBA, each font pixel <paramref name="scale"/> pixels wide, with a
    /// margin of two font pixels around.</summary>
    public static Pixels Render(string text, int scale)
    {
        var drawn = Drawn(text);
        int width = (drawn.Length * 6 + 3) * scale, height = 11 * scale;
        var data = new byte[width * height * 4];
        for (var i = 0; i < width * height; i++)
        {
            (data[i * 4], data[i * 4 + 1], data[i * 4 + 2], data[i * 4 + 3]) = (16, 18, 22, 255);
        }

        for (var at = 0; at < drawn.Length; at++)
        {
            var glyph = Glyphs[drawn[at]];
            for (var row = 0; row < 7; row++)
            {
                for (var column = 0; column < 5; column++)
                {
                    if ((glyph[row] & (0x10 >> column)) == 0)
                    {
                        continue;
                    }

                    for (var y = (2 + row) * scale; y < (3 + row) * scale; y++)
                    {
                        for (var x = (2 + at * 6 + column) * scale; x < (3 + at * 6 + column) * scale; x++)
                        {
                            var pixel = (y * width + x) * 4;
                            (data[pixel], data[pixel + 1], data[pixel + 2]) = (255, 255, 255);
                        }
                    }
                }
            }
        }

        return new Pixels(width, height, 4, data);
    }
}
